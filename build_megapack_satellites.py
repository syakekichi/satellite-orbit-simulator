def verify_and_patch():
    print(f"Total Megapack Satellites: {len(MEGAPACK_SATELLITES)}")
    over_list = []
    for sat in MEGAPACK_SATELLITES:
        full_text = f"{sat['story_ja']}\n\n{LINK_GUIDE_JA}\n{sat['tags']}"
        w = calc_x_text_weight(full_text)
        if w > 276:
            over_list.append((sat["name"], w, full_text))

    if over_list:
        print(f"❌ {len(over_list)} satellites exceed 276 weight limit:")
        for name, w, t in over_list:
            print(f"- {name}: {w}")
        return False

    print(f"✅ ALL {len(MEGAPACK_SATELLITES)} satellites strictly passed verification! (All weights <= 276)")

    # bot_master.py に注入
    with open("bot_master.py", "r", encoding="utf-8") as f:
        code = f.read()

    start_str = "# Mode 8: Unique Satellite Spotlight"
    start_pos = code.find(start_str)
    if start_pos == -1:
        start_str = "FEATURED_SATELLITES = ["
        start_pos = code.find(start_str)

    end_str = "def task_satellite_spotlight():"
    end_pos = code.find(end_str)

    if start_pos == -1 or end_pos == -1:
        print("❌ Could not find markers in bot_master.py")
        return False

    header = f"# Mode 8: Unique Satellite Spotlight (注目衛星スポットライト - 圧巻の全{len(MEGAPACK_SATELLITES)}選)\n# -------------------------------------------------------------\nFEATURED_SATELLITES = "
    body = pprint.pformat(MEGAPACK_SATELLITES, indent=4, width=120, sort_dicts=False)
    footer = "\n\n"

    new_section = header + body + footer
    new_code = code[:start_pos] + new_section + code[end_pos:]

    with open("bot_master.py", "w", encoding="utf-8") as f:
        f.write(new_code)

    print(f"🎉 Successfully injected all {len(MEGAPACK_SATELLITES)} Megapack satellites into bot_master.py!")
    return True

if __name__ == "__main__":
    verify_and_patch()
